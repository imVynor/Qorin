@dataclass
class NormalizedDocument:
    text: str
    source: str
    document_id: str
    char_count: int
    byte_count: int
    content_hash: str
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "NormalizedDocument":
        return cls(**data)


def compute_content_hash(text: str) -> str:
    """Compute deterministic SHA-256 content hash of normalized text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def normalize_record(
    raw_record: Dict[str, Any],
    source_config: SourceConfig,
    min_chars: int = 50,
) -> Optional[NormalizedDocument]:
    """Normalize raw dataset record into NormalizedDocument.

    Filters out empty, whitespace-only, or too-short documents.
    Applies per-source quality, licensing, and noise filtering.
    """
    # Code-specific quality, licensing, and noise filters
    if source_config.source_name == "codeparrot-clean":
        lic = (raw_record.get("license") or "").strip().lower()
        if lic not in PERMISSIVE_CODE_LICENSES:
            return None

        if raw_record.get("autogenerated", False):
            return None

        line_max = raw_record.get("line_max")
        if line_max is not None and line_max > 1000:
            return None

        alpha_frac = raw_record.get("alpha_frac")
        if alpha_frac is not None and alpha_frac < 0.25:
            return None

    raw_text = raw_record.get(source_config.text_column)
    if not isinstance(raw_text, str):
        return None

    cleaned_text = raw_text.strip()
    if len(cleaned_text) < min_chars:
        return None

    utf8_bytes = len(cleaned_text.encode("utf-8"))
    content_hash = compute_content_hash(cleaned_text)

    # Determine stable document_id
    doc_id = None
    if source_config.id_column and source_config.id_column in raw_record:
        val = raw_record[source_config.id_column]
        if val:
            doc_id = f"{source_config.source_name}:{val}"

    if not doc_id:
        doc_id = f"{source_config.source_name}:{content_hash[:16]}"

    metadata = {
        "dataset_id": source_config.dataset_id,
        "config_name": source_config.config_name,
        "revision": source_config.revision,
        "license": raw_record.get("license", source_config.license),
    }

    # Extract useful auxiliary fields if present without logging sensitive info
    for extra_field in (
        "score",
        "int_score",
        "audience",
        "format",
        "token_count",
        "token_length",
        "repo_name",
        "path",
        "line_mean",
        "line_max",
        "alpha_frac",
    ):
        if extra_field in raw_record and raw_record[extra_field] is not None:
            metadata[extra_field] = raw_record[extra_field]

    return NormalizedDocument(
        text=cleaned_text,
        source=source_config.source_name,
        document_id=doc_id,
        char_count=len(cleaned_text),
        byte_count=utf8_bytes,
        content_hash=content_hash,
        metadata=metadata,
    )


def stream_dataset_records(
    source_config: SourceConfig,
    max_documents: Optional[int] = None,
    max_bytes: Optional[int] = None,
    max_tokens: Optional[int] = None,
    tokenizer: Optional[Any] = None,
    min_chars: int = 50,
    deduplicate: bool = True,
    seen_hashes: Optional[Set[str]] = None,
    max_retries: int = 3,
    retry_delay: float = 2.0,
) -> Iterator[NormalizedDocument]:
    """Stream and yield normalized documents bounded by count, byte, or token budget.

    Handles network retries, empty record filtering, conservative deduplication, and measured token bounds.
    """
    from datasets import load_dataset

    if seen_hashes is None and deduplicate:
        seen_hashes = set()
    docs_yielded = 0
    bytes_yielded = 0
    tokens_yielded = 0

    attempt = 0
    while attempt < max_retries:
        try:
            logger.info(
                "Streaming from %s (config: %s, split: %s, rev: %s)...",
                source_config.dataset_id,
                source_config.config_name,
                source_config.split,
                source_config.revision,
            )
            dataset = load_dataset(
                source_config.dataset_id,
                name=source_config.config_name,
                split=source_config.split,
                revision=source_config.revision,
                streaming=True,
            )
            break
        except Exception as err:
            attempt += 1
            logger.warning(
                "Error connecting to %s (attempt %d/%d): %s",
                source_config.dataset_id,
                attempt,
                max_retries,
                err,
            )
            if attempt >= max_retries:
                raise RuntimeError(
                    f"Failed to stream from {source_config.dataset_id} after {max_retries} attempts: {err}"
                ) from err
            time.sleep(retry_delay * attempt)

    for raw_record in dataset:
        doc = normalize_record(raw_record, source_config, min_chars=min_chars)
        if doc is None:
            continue

        if seen_hashes is not None:
            if doc.content_hash in seen_hashes:
                continue
            seen_hashes.add(doc.content_hash)

        yield doc
        docs_yielded += 1
        bytes_yielded += doc.byte_count

        if tokenizer is not None:
            tok_count = len(tokenizer.encode(doc.text)) + 1
            tokens_yielded += tok_count

        if docs_yielded % 1000 == 0 or (docs_yielded < 1000 and docs_yielded % 500 == 0):
            pct_str = f", {tokens_yielded / max_tokens * 100:.1f}%" if max_tokens else ""
            logger.info(
                "[%s] Streamed %d docs (%.2f MB, %d tokens%s)...",
                source_config.source_name,
                docs_yielded,
                bytes_yielded / (1024 * 1024),
                tokens_yielded,
                pct_str,
            )

        if tokenizer is not None and max_tokens is not None and tokens_yielded >= max_tokens:
            break
        if max_documents is not None and docs_yielded >= max_documents:
            break
        if max_bytes is not None and bytes_yielded >= max_bytes:
            break


def verify_source(source_config: SourceConfig, sample_size: int = 3) -> Dict[str, Any]:
    """Verify dataset connectivity, fields, and normalization with a small sample."""
    docs = []
    errors = []
    start_time = time.perf_counter()

    try:
        for doc in stream_dataset_records(source_config, max_documents=sample_size, deduplicate=True):
            docs.append({
                "document_id": doc.document_id,
                "char_count": doc.char_count,
                "byte_count": doc.byte_count,
                "content_hash": doc.content_hash[:12] + "...",
                "metadata": doc.metadata,
                "preview": doc.text[:120].replace("\n", " "),
            })
    except Exception as exc:
        errors.append(str(exc))

    elapsed = time.perf_counter() - start_time
    return {
        "source": source_config.source_name,
        "dataset_id": source_config.dataset_id,
        "config_name": source_config.config_name,
        "revision": source_config.revision,
        "license": source_config.license,
        "success": len(docs) > 0 and len(errors) == 0,
        "samples_retrieved": len(docs),
        "elapsed_seconds": round(elapsed, 3),
        "samples": docs,
        "errors": errors,
    }
