def hash_string(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()

def measure_tokens(messages: List[Dict[str, str]]) -> Tuple[int, int]:
    enc = serializer.encode_conversation(messages, max_length=2048, append_eos=True)
    conv_tok = (enc["input_ids"] != 0).sum().item()
    asst_tok = (enc["labels"] != -100).sum().item()
    return conv_tok, asst_tok

