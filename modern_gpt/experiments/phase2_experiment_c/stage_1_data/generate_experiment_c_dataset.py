# 4. Multi-Step Execution & Error Recovery Generator
# ----------------------------------------------------------------------
def generate_multistep_and_recovery_records(target_count: int = 800, seed: int = 42) -> List[Dict[str, Any]]:
    print(f"Generating {target_count} multi-step and error recovery records...")
    rng = random.Random(seed)
    records = []

    for i in range(target_count):
        is_error_recovery = (i % 2 == 0)

        if is_error_recovery:
            # Trajectory: Prompt -> Buggy Code -> <|tool_error|> -> Diagnosed Fix -> <|tool_result|> -> Final Answer
            val = rng.randint(10, 500)
            user_msg = f"Calculate the square root of {val*val} using math.isqrt in Python."
            buggy_code = f"res = math.isqrt({val*val})\nprint(res)"
            
            # Execute buggy code to capture REAL NameError
            err_res = sandbox.execute(buggy_code)
            assert err_res.exit_code != 0

            # Execute fixed code
            fixed_code = f"import math\nres = math.isqrt({val*val})\nprint('Square Root:', res)"
            fix_res = sandbox.execute(fixed_code)
            assert fix_res.exit_code == 0

            call_err = json.dumps({"name": "python", "arguments": {"code": buggy_code}})
            obs_err = json.dumps(err_res.to_dict())
            call_fix = json.dumps({"name": "python", "arguments": {"code": fixed_code}})
            obs_fix = json.dumps(fix_res.to_dict())

            messages = [
                {"role": "system", "content": COMPACT_MANIFEST},
                {"role": "user", "content": user_msg},
                {"role": "assistant", "content": f"<|tool_call|>{call_err}"},
                {"role": "tool", "content": f"<|tool_error|>{obs_err}"},
                {"role": "assistant", "content": f"The previous execution failed with `NameError: name 'math' is not defined` because the `math` module was not imported. Here is the corrected code:\n<|tool_call|>{call_fix}"},
                {"role": "tool", "content": f"<|tool_result|>{obs_fix}"},
                {"role": "assistant", "content": f"The corrected script executed successfully with output `{fix_res.stdout.strip()}`. The square root of {val*val} is {val}."}
            ]

            prov = "PythonSandbox:live_error_recovery_trajectory"
        else:
            # Multi-Step: Step 1 calculation -> Step 2 downstream calculation
            n1 = rng.randint(10, 50)
            n2 = rng.randint(2, 6)
            user_msg = f"First compute the sum of squares from 1 to {n1} using Python, then find the remainder when divided by {n2} in a second step."
            
            code_1 = f"s = sum(x**2 for x in range(1, {n1+1}))\nprint('Sum of squares:', s)"
            res_1 = sandbox.execute(code_1)
            assert res_1.exit_code == 0
            s_val = int(res_1.stdout.split(":")[1].strip())

            code_2 = f"rem = {s_val} % {n2}\nprint('Remainder:', rem)"
            res_2 = sandbox.execute(code_2)
            assert res_2.exit_code == 0
            rem_val = int(res_2.stdout.split(":")[1].strip())

            call_1 = json.dumps({"name": "python", "arguments": {"code": code_1}})
            obs_1 = json.dumps(res_1.to_dict())
            call_2 = json.dumps({"name": "python", "arguments": {"code": code_2}})
            obs_2 = json.dumps(res_2.to_dict())

            messages = [
                {"role": "system", "content": COMPACT_MANIFEST},
                {"role": "user", "content": user_msg},
                {"role": "assistant", "content": f"<|tool_call|>{call_1}"},
                {"role": "tool", "content": f"<|tool_result|>{obs_1}"},
                {"role": "assistant", "content": f"Step 1 completed with sum of squares = {s_val}. Now calculating remainder modulo {n2}:\n<|tool_call|>{call_2}"},
                {"role": "tool", "content": f"<|tool_result|>{obs_2}"},
                {"role": "assistant", "content": f"The two-step computation concluded successfully:\n1. Sum of squares from 1 to {n1} = {s_val}.\n2. Divided by {n2}, the remainder is {rem_val}."}
            ]

            prov = "PythonSandbox:live_multistep_trajectory"

        conv_tok, asst_tok = measure_tokens(messages)
        records.append({
            "id": f"exp_c_multistep_{i+1:05d}",
            "category": "multistep_and_error_recovery",
            "tool_name": "python",
            "provenance": prov,
            "execution_verified": True,
            "messages": messages,
            "conv_tokens": conv_tok,
            "asst_tokens": asst_tok
        })

    print(f"Generated {len(records)} multi-step & error recovery records.")
    return records

