# Main Dataset Assembly & Split Generation
# ----------------------------------------------------------------------
def main():
    print("=== Building Experiment C Targeted Dataset ===")
    
    py_records = generate_authentic_python_records(target_count=1500)
    web_records = generate_authentic_web_records(target_count=80)
    auth_records = py_records + web_records

    control_records = generate_negative_and_intent_controls(target_count=1100)
    multistep_records = generate_multistep_and_recovery_records(target_count=800)
    retention_records = sample_retention_records(target_count=700)

    all_records = auth_records + control_records + multistep_records + retention_records

    # Deterministic Shuffle
    rng = random.Random(42)
    rng.shuffle(all_records)

    total_conv_tokens = sum(r["conv_tokens"] for r in all_records)
    total_asst_tokens = sum(r["asst_tokens"] for r in all_records)
    print(f"\nTotal Dataset Records: {len(all_records):,}")
    print(f"Total Serialized Conversation Tokens: {total_conv_tokens:,}")
    print(f"Total Assistant-Supervised Tokens: {total_asst_tokens:,}")

    # Category Accounting
    cat_accounting = {}
    for r in all_records:
        cat = r["category"]
        if cat not in cat_accounting:
            cat_accounting[cat] = {"records": 0, "conv_tokens": 0, "asst_tokens": 0}
        cat_accounting[cat]["records"] += 1
        cat_accounting[cat]["conv_tokens"] += r["conv_tokens"]
        cat_accounting[cat]["asst_tokens"] += r["asst_tokens"]

    print("\n--- Actual Category Distribution ---")
    for cat, d in cat_accounting.items():
        pct_conv = (d["conv_tokens"] / total_conv_tokens) * 100
        print(f"  {cat}: {d['records']:,} records | {d['conv_tokens']:,} conv tokens ({pct_conv:.1f}%) | {d['asst_tokens']:,} asst tokens")

    # Split into 95% Train / 5% Validation
    val_count = int(len(all_records) * 0.05)
    train_records = all_records[val_count:]
    val_records = all_records[:val_count]

    train_file = DATA_DIR / "train.jsonl"
