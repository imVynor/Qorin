# 5. General & Coding Retention Controls (from SFT v1.1 Train Split)
# ----------------------------------------------------------------------
def sample_retention_records(target_count: int = 800, seed: int = 42) -> List[Dict[str, Any]]:
    print(f"Sampling {target_count} general & coding retention records from SFT v1.1 train split...")
    train_split = REPO_ROOT / "modern_gpt/data_sft_release/splits/train.jsonl"
    
    gen_candidates = []
    code_candidates = []

    with open(train_split, "r", encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            cat = r.get("category")
            if cat == "general_instructions":
                gen_candidates.append(r)
            elif cat == "coding":
                code_candidates.append(r)

    rng = random.Random(seed)
    rng.shuffle(gen_candidates)
    rng.shuffle(code_candidates)

    selected = gen_candidates[:target_count // 2] + code_candidates[:target_count // 2]
    records = []

    for idx, r in enumerate(selected):
        # Update system prompt to compact manifest
        msgs = list(r["messages"])
        if msgs and msgs[0]["role"] == "system":
            msgs[0]["content"] = COMPACT_MANIFEST
        else:
            msgs.insert(0, {"role": "system", "content": COMPACT_MANIFEST})

        conv_tok, asst_tok = measure_tokens(msgs)
        records.append({
            "id": f"exp_c_retention_{idx+1:05d}",
            "category": "general_and_coding_retention",
            "tool_name": "none",
            "provenance": f"SFT_v1.1_train_partition:{r.get('source_name', 'unknown')}",
            "execution_verified": False,
            "messages": msgs,
            "conv_tokens": conv_tok,
            "asst_tokens": asst_tok
        })

    print(f"Sampled {len(records)} retention records.")
    return records

